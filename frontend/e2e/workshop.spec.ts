import { test, expect } from '@playwright/test'

test.beforeEach(async({request})=>{
  await request.post('/api/admin/all/control',{headers:{Authorization:'Bearer test-secret'},data:{action:'reset'}})
})

test('un trinôme retrouve, montre, délègue, valide, exporte et est réinitialisé', async({page,request})=>{
  const errors:string[]=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('link',{name:/Trinôme 01/})).toBeVisible()
  await page.getByRole('link',{name:/Trinôme 01/}).click()
  const sid=page.url().split('/g/')[1]
  const state=async()=> (await request.get('/api/sessions/'+sid)).json()
  await page.getByRole('button',{name:/Se souvenir/}).click()
  await page.getByRole('textbox',{name:'Rechercher dans la mémoire'}).fill('accessibilité')
  await page.getByRole('button',{name:'Rechercher',exact:true}).click()
  const memory=page.locator('.memory-card').filter({hasText:'Décision accessibilité confirmée'})
  await memory.getByRole('button',{name:/Ajouter au contexte/}).click()
  await expect(page.locator('.context-summary')).toContainText('140 cm')
  await page.getByRole('button',{name:'Retirer m-access'}).click()
  await expect(page.locator('.context-summary')).toContainText('90 cm')
  await memory.getByRole('button',{name:/Ajouter au contexte/}).click()
  await page.getByRole('button',{name:/Montrer/}).click()
  await page.getByRole('button',{name:'Enregistrer',exact:true}).click()
  await page.getByRole('button',{name:/Îlot découverte A/}).click()
  await page.getByLabel("Zone d'affectation").selectOption('atelier')
  await page.getByRole('button',{name:/Affecter la ressource/}).click()
  await expect.poll(async()=> (await state()).state.recorded.length).toBe(1)
  await page.getByLabel('Début du créneau').fill('10:00')
  await page.getByRole('button',{name:/Affecter la ressource/}).click()
  await expect.poll(async()=> (await state()).state.recorded.length).toBe(2)
  await page.getByRole('button',{name:"J'ai terminé",exact:true}).click()
  await expect(page.locator('.learning-panel')).toContainText('resource_id')
  await page.getByRole('button',{name:/Îlot découverte A/}).click()
  await page.getByRole('button',{name:/Îlot découverte B/}).click()
  await page.getByRole('button',{name:'Fais-le pour moi',exact:true}).click()
  await expect.poll(async()=> (await state()).state.assignments['table-b']?.start).toBe('10:00')
  await page.getByRole('button',{name:/Déléguer/}).click()
  await page.getByRole('button',{name:'Préparer la mission',exact:true}).click()
  await expect(page.locator('.decision-card')).toContainText('À VALIDER PAR LE SUPERVISEUR')
  expect((await state()).state.documents).toHaveLength(0)
  await page.getByRole('button',{name:'Refuser',exact:true}).click()
  await expect(page.locator('.decision-card')).toContainText('PROPOSITION REFUSÉE')
  await page.getByRole('button',{name:'Préparer la mission',exact:true}).click()
  await expect(page.getByRole('button',{name:'Valider',exact:true})).toBeEnabled()
  await page.getByRole('button',{name:'Valider',exact:true}).click()
  await expect(page.locator('.decision-card')).toContainText('DÉCISION EXÉCUTÉE')
  await expect.poll(async()=> (await state()).state.documents.length).toBe(1)
  await page.getByRole('button',{name:"Plan d'ouverture HORIZON",exact:true}).click()
  await expect(page.getByRole('dialog')).toContainText('5700')
  await page.getByRole('button',{name:'Fermer le document'}).click()
  await page.getByRole('button',{name:/Restituer/}).click()
  const downloadPromise=page.waitForEvent('download')
  await page.getByRole('link',{name:'Exporter le résumé et la trace'}).click()
  expect((await downloadPromise).suggestedFilename()).toBe('work2030-resume.md')
  expect(errors).toEqual([])
  await page.screenshot({path:'../runtime/work2030-browser.png',fullPage:true})
  const facilitator=await page.context().newPage()
  await facilitator.goto('/animateur')
  await facilitator.getByLabel('Code animateur (ANIMATOR_TOKEN)').fill('test-secret')
  await facilitator.getByRole('button',{name:/Ouvrir la console/}).click()
  const group=facilitator.locator('.admin-group').filter({has:facilitator.getByRole('heading',{name:'Trinôme 01',exact:true})})
  await group.getByRole('button',{name:'Reset',exact:true}).click()
  await facilitator.getByRole('dialog').getByRole('button',{name:'Réinitialiser',exact:true}).click()
  await expect.poll(async()=> (await state()).state.documents.length).toBe(0)
  await expect(page.locator('.context-summary')).toContainText('90 cm')
})

test('les objets visuels, annotations et cartes physiques modifient des données',async({page,request})=>{
  const groups=await (await request.get('/api/sessions')).json()
  const sid=groups[1].id
  await page.goto('/g/'+sid+'?card=ACCES140')
  await page.getByRole('button',{name:'Ajouter la carte',exact:true}).click()
  await expect(page.locator('.context-summary')).toContainText('140 cm')
  await page.getByRole('button',{name:'Entourer une zone',exact:true}).click()
  const plan=page.getByRole('img',{name:'Plan interactif des zones HORIZON'})
  const box=(await plan.boundingBox())!
  await page.mouse.move(box.x+box.width*.1,box.y+box.height*.65)
  await page.mouse.down()
  await page.mouse.move(box.x+box.width*.4,box.y+box.height*.65,{steps:10})
  await page.mouse.move(box.x+box.width*.4,box.y+box.height*.85,{steps:10})
  await page.mouse.move(box.x+box.width*.1,box.y+box.height*.85,{steps:10})
  await page.mouse.up()
  await expect.poll(async()=> (await (await request.get('/api/sessions/'+sid)).json()).state.annotations.length).toBe(1)
  await page.getByRole('button',{name:'Annuler la dernière modification'}).click()
  await expect.poll(async()=> (await (await request.get('/api/sessions/'+sid)).json()).state.annotations.length).toBe(0)
  await page.getByRole('button',{name:'Sélectionner',exact:true}).click()
  await page.getByRole('button',{name:/Ressources/}).click()
  await page.getByRole('button',{name:/Mur LED silencieux/}).click()
  await page.getByRole('button',{name:'Zone Fabrique',exact:true}).click()
  await page.getByRole('button',{name:'Préparer la mission',exact:true}).click()
  await expect(page.locator('.decision-card')).toContainText('Sélection visuelle')
  await page.getByRole('button',{name:'Valider',exact:true}).click()
  await expect.poll(async()=> (await (await request.get('/api/sessions/'+sid)).json()).state.assignments.led?.zone).toBe('atelier')
})
